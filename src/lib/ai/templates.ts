function toSeed(row: (string | number)[]): Seed {
  return {
    name: String(row[0]),
    share: Number(row[1]),
    frequency: String(row[2]),
    mode: row[3] as ExecutionMode,
    reason: String(row[4]),
    confidence: Number(row[5]),
  };
}

export function decomposeRoleOffline(title: string): RoleTask[] {
  const seeds = seedsFor(title);
  return seeds.map((seed) => ({
    id: uid("task"),
    name: seed.name,
    timeShare: seed.share / 100,
    frequency: seed.frequency,
    mode: seed.mode,
    reason: seed.reason,
    confidence: seed.confidence,
    source: "template" as const,
    edited: false,
  }));
}
